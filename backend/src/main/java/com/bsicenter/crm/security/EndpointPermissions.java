  private static void add(String method,String path,String permission){
    String regex=Arrays.stream(path.split("/",-1)).map(s->s.startsWith("{")?"[^/]+":Pattern.quote(s)).reduce((a,b)->a+"/"+b).orElse("");
    RULES.add(new Rule(method,path,permission,Pattern.compile("^"+regex+"$")));
  }
  public static List<Rule> rules(){return List.copyOf(RULES);}
  public static String required(String method,String path){
    String verb=method.equals("HEAD")?"GET":method;
    return RULES.stream().filter(r->r.method.equals(verb)&&r.pattern.matcher(path).matches()).findFirst().map(Rule::permission).orElse(null);
  }
